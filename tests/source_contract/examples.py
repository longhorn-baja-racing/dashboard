@dataclass(frozen=True)
class Fixture:
    source_id: str
    epoch: int
    models: tuple[SimulatedSignal, ...]
    expected: tuple[SourceEvent, ...]

    @property
    def schema(self) -> SignalSchema:
        return SignalSchema(1, tuple(model.descriptor for model in self.models))


def fixture(family: str) -> Fixture:
    if family == "process":
        source, epoch = "COM3/Rig-A", -7
        fast, slow = "process.pressure", "process.temperature"
        kind, fast_unit, slow_unit = "numeric", "Pa", "°C"
        fast_values, slow_values = (0, 7, 8, 9), (20, 21)
    else:
        source, epoch = "AA:BB:CC", 2**60 + 13
        fast, slow = "motion.enabled", "motion.angle"
        kind, fast_unit, slow_unit = "boolean", "bool", "deg"
        fast_values, slow_values = (False, True, False, True), (-1, 2)

    def descriptor(name: str, data_type: str, unit: str, rate: int) -> SignalDescriptor:
        return SignalDescriptor(
            name,
            "Reading",
            (family,),
            data_type,
            source,
            device_id="Device-A",
            canonical_unit=unit,
            nominal_rate_hz=rate,
            timestamp_domain="relative",
        )

    fast_model = SimulatedSignal(
        descriptor(fast, kind, fast_unit, 4), fast_values, unavailable=((2, 3),)
    )
    slow_model = SimulatedSignal(descriptor(slow, "numeric", slow_unit, 1), slow_values)

    # Independent known schedule and values: never generated by running the adapter under test.
    known = [
        (fast, i * 250_000_000, value, fast_unit, i != 2)
        for i, value in enumerate(
            (fast_values[0], fast_values[1], None, fast_values[3], fast_values[0])
        )
    ]
    known += [
        (slow, 0, slow_values[0], slow_unit, True),
        (slow, 1_000_000_000, slow_values[1], slow_unit, True),
    ]
    expected = tuple(
        SourceEvent(
            SourceEventKind.RECORD,
            source,
            signal_id=name,
            sample=SignalSample(
                epoch + offset,
                value,
                available=available,
                quality="simulated" if available else "simulated_unavailable",
                source_id=source,
                unit=unit,
                timestamp_domain="relative",
            ),
        )
        for name, offset, value, unit, available in sorted(known, key=lambda row: (row[1], row[0]))
    )
    return Fixture(
        source,
        epoch,
        tuple(sorted((fast_model, slow_model), key=lambda item: item.descriptor.identifier)),
        expected,
    )


def csv_file(path: Path, spec: Fixture, events: tuple[SourceEvent, ...] | None = None) -> None:
    """contract-fixture-v1: long rows, explicit IDs/ns/units/availability; UTF-8 JSON values."""
    with path.open("w", newline="", encoding="utf-8") as file:
        writer = csv.writer(file)
        writer.writerow(("signal", "time_ns", "value", "available", "quality", "unit", "source"))
        for event in spec.expected if events is None else events:
            assert event.sample is not None
            sample = event.sample
            writer.writerow(
                (
                    event.signal_id,
                    sample.timestamp_ns,
                    json.dumps(sample.value),
                    int(sample.available),
                    sample.quality,
                    sample.unit,
                    event.source_id,
                )
            )


def wait_for_cancel(token: CancellationToken) -> None:
    while not token.is_cancelled:
        token.wait(0.001)
    token.raise_if_cancelled()


def read_csv(path: Path, token: CancellationToken, *, pause_open: bool) -> Iterator[SourceEvent]:
    with path.open(newline="", encoding="utf-8") as file:
        if pause_open:
            wait_for_cancel(token)
        for row in csv.DictReader(file):
            token.raise_if_cancelled()
            yield SourceEvent(
                SourceEventKind.RECORD,
                row["source"],
                signal_id=row["signal"],
                sample=SignalSample(
                    int(row["time_ns"]),
                    json.loads(row["value"]),
                    available={"0": False, "1": True}[row["available"]],
                    quality=row["quality"],
                    source_id=row["source"],
                    unit=row["unit"],
                    timestamp_domain="relative",
                ),
            )


def make_run(
    kind: str,
    spec: Fixture,
    path: Path,
    *,
    scenario: str = "normal",
    capacity: int = 32,
) -> AdapterRun:
    if kind == "simulator":
        now = [0]

        def wait(token: CancellationToken, delay: int) -> None:
            # Yield time to observe a full live queue; advance the schedule with virtual time.
            token.wait(0.001)
            now[0] += delay

        return AdapterRun(
            SimulatorSource(
                spec.models,
                start_ns=spec.epoch,
                duration_ns=None if scenario == "live" else 1_000_000_000,
                realtime=scenario == "live",
                capacity=capacity,
                publish_timeout=0,
                disconnect_after_ns=500_000_001 if scenario == "error" else None,
                now_ns=lambda: now[0],
                wait=wait,
            )
        )

    active = Event()
    sequence = spec.expected
    if scenario == "out_of_order":
        sequence = (sequence[2], sequence[0], sequence[0], *sequence[1:])
    if kind == "csv":
        csv_file(path, spec, sequence)

    def generate(token: CancellationToken) -> Iterator[SourceEvent]:
        active.set()
        try:
            if kind == "csv":
                iterator = read_csv(path, token, pause_open=scenario == "opening")
            else:
                if scenario == "opening":
                    wait_for_cancel(token)
                iterator = iter(sequence)
            try:
                for index, event in enumerate(iterator):
                    token.raise_if_cancelled()
                    if scenario == "error" and index == 1:
                        raise OSError("fixture reader disconnected after one sample")
                    if scenario == "bad" and index == 1:
                        event = replace(event, signal_id="unregistered.signal")
                    yield event
            finally:
                closer = getattr(iterator, "close", None)
                if closer is not None:
                    closer()
            if scenario == "live":
                for event in cycle(spec.expected):
                    token.raise_if_cancelled()
                    yield event
        finally:
            active.clear()

    source = IteratorSource(
        spec.source_id,
        spec.schema,
        generate,
        capacity=capacity,
        is_live=scenario == "live",
        publish_timeout=0,
    )
    return AdapterRun(source, lambda: not active.is_set())


class ControllableFake(IteratorSource):
    """Deterministic seek and delivery-schedule probe; sample timestamps stay untouched."""

    def __init__(self, spec: Fixture) -> None:
        self.cursor = spec.epoch
        self.rate = 1.0
        self.arrival_ns: list[int] = []

        def generate(token: CancellationToken) -> Iterator[SourceEvent]:
            elapsed = 0
            previous = self.cursor
            self.arrival_ns.clear()
            for event in spec.expected:
                assert event.sample is not None
                time = event.sample.timestamp_ns
                if time < self.cursor:
                    continue
                token.raise_if_cancelled()
                elapsed += int((time - previous) / self.rate)
                self.arrival_ns.append(elapsed)
                previous = time
                yield event

        super().__init__(spec.source_id, spec.schema, generate)

    @property
    def capabilities(self) -> SourceCapabilities:
        return SourceCapabilities(False, True, True, 128)

    def seek(self, timestamp_ns: int) -> None:
        self.cursor = timestamp_ns

    def set_rate(self, rate_hz: float) -> None:
        if not isfinite(rate_hz) or rate_hz <= 0:
            raise ValueError("delivery rate must be finite and positive")
        self.rate = rate_hz
